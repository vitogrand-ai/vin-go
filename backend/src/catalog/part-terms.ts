/**
 * Весь словарь — для замера покрытия по каталогу (`catalog:terms`). Термин
 * проверяется живым вызовом на машинах РАЗНЫХ каталогов: у 17vin база то
 * китайская, то английская, и термин, проверенный на одной машине, на другой
 * молчит (см. разбор Jaguar XF в docs/CATALOG_ADAPTERS.md).
 */
export const PART_TERM_ENTRIES: readonly DictEntry[] = DICT

/** Нормализация запроса: регистр, ё→е, разбиение на буквенно-цифровые токены. */
function tokenize(query: string): string[] {
  return query
    .toLowerCase()
    .replaceAll('ё', 'е')
    .split(/[^a-zа-я0-9]+/)
    .filter(Boolean)
}

/** Самая специфичная запись словаря для запроса (правило выбора — см. выше). */
function lookup(query: string): DictEntry | null {
  const tokens = tokenize(query)
  if (tokens.length === 0) return null

  let best: DictEntry | null = null
  for (const entry of DICT) {
    if (best && entry.stems.length <= best.stems.length) continue // ранняя запись выигрывает при равенстве
    if (entry.stems.every((stem) => tokens.some((token) => token.startsWith(stem)))) {
      best = entry
    }
  }
  return best
}

/**
 * Русский запрос → китайский EPC-термин для поиска 17vin.
 * null — перевод не найден (вызывающая сторона решает, что делать: для 17vin
 * честнее вернуть пустой список, чем показать шумную выдачу всего каталога).
 */
export function translatePartQuery(query: string): string | null {
  return lookup(query)?.zh ?? null
}

/**
 * Английские подстроки, по которым название детали считается отвечающим
 * запросу. Пусто — запроса нет в словаре.
 *
 * Намеренно только английские: локализованное название деталь получает вместе
 * с местом в универсальном дереве каталога, то есть вместе с `nameId`, по
 * которому она и так находится точным попаданием. Русские стемы здесь дали бы
 * только ложные срабатывания — «масл» ловит «Пробка маслосливного отверстия».
 */
export function englishPartTerms(query: string): string[] {
  return lookup(query)?.en ?? []
}
