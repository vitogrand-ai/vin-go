/**
 * Модельный год из самого VIN (ISO 3779, 10-я позиция).
 *
 * Зачем это нам: каталог по одному VIN нередко отдаёт НЕСКОЛЬКО модификаций
 * разных поколений (живой случай: VW Jetta 1992 и Jetta 2022 по одному номеру),
 * и выбирать между ними вслепую нельзя — у них разные детали. Год из VIN даёт
 * независимую подсказку, какую из модификаций каталог имеет в виду.
 *
 * Чему верить нельзя: год кодируют не все производители. Европейские Mercedes
 * и BMW ставят на 10-ю позицию не год (у W177 там «1», что дало бы «2001» на
 * машине 2019 года — так и врёт бесплатный декодер NHTSA). Поэтому результат
 * этой функции — только ГИПОТЕЗА: годится, если её подтверждает сам каталог,
 * и не годится как самостоятельный источник года для карточки.
 */

/**
 * Коды года по порядку: A=1980 … Y=2000, 1=2001 … 9=2009, дальше цикл
 * повторяется (A=2010 … Y=2030). Буквы I, O, Q, U, Z и ноль не используются —
 * их слишком легко спутать с цифрами.
 */
const YEAR_CODES = 'ABCDEFGHJKLMNPRSTVWXY123456789'

/**
 * Год из VIN или null, если номер года не кодирует (frame-номер JDM, чужой код
 * на 10-й позиции) либо получается неправдоподобный.
 *
 * Цикл в 30 лет разводится стандартным правилом NHTSA: буква на 7-й позиции
 * — цикл 2010+, цифра — 1980-2009. Живая проверка: `LFV3B2FY2N3102396` —
 * 7-я позиция «F», 10-я «N» → 2022 (каталог подтверждает: «2020-2027»), а не
 * 1992 из первого цикла.
 */
export function vinModelYear(vinOrFrame: string): number | null {
  const vin = vinOrFrame.trim().toUpperCase()
  if (vin.length !== 17) return null

  const index = YEAR_CODES.indexOf(vin[9]!)
  if (index < 0) return null

  const modernCycle = /[A-Z]/.test(vin[6]!)
  const year = (modernCycle ? 2010 : 1980) + index
  // Машина из будущего — значит правило к этому VIN не применимо.
  return year <= new Date().getFullYear() + 1 ? year : null
}
