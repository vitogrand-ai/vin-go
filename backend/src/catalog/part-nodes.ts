/**
 * Строка таблицы для запроса мастера; null — формулировки в таблице нет.
 *
 * Деталь в запросе названа ПЕРВОЙ, дальше идут уточнения: «шкив коленвала» —
 * это шкив, «вкладыши коренные коленвала» — вкладыши. Поэтому строка годится,
 * только если перед найденным словом стоят одни прилагательные («передняя
 * стойка», «масляный фильтр»). Живьём 23.09.2026 словарь жаргона превращал
 * «вкладыши» во «вкладыши коренные коленвала», и строка «коленвал» отдавала
 * коленвал на восьми машинах. Запрос, где деталь таблице неизвестна («шкив
 * коленвала»), уходит в прежний поиск по словам, а не в соседнюю деталь.
 */
export function partNodeFor(query: string): PartNode | null {
  const q = query.toLowerCase().replaceAll('ё', 'е').replace(/\s+/g, ' ').trim()
  if (!q) return null
  for (const node of PART_NODES) {
    const match = new RegExp(node.ask.source, node.ask.flags.replace('g', '')).exec(q)
    if (!match) continue
    const before = q.slice(0, match.index).trim()
    if (before && !before.split(' ').every((word) => ADJECTIVE.test(word))) continue
    return node
  }
  return null
}

/** Прилагательное (полная форма): «передняя», «масляный», «тормозные», «левого». */
const ADJECTIVE = /(ый|ий|ой|ая|яя|ое|ее|ые|ие|ого|его|ую|юю|ых|их)$/

/**
 * Та ли это деталь. С кодом — только по коду: чужой код значит чужую деталь,
 * как бы ни было похоже название. Без кода — по запасному шаблону.
 */
export function isNodePart(node: PartNode, part: { name: string; nameId: string | null }): boolean {
  if (part.nameId !== null) return node.ids.includes(part.nameId)
  if (!node.other?.test(part.name)) return false
  return !(node.not?.test(part.name) ?? false)
}
