/**
 * Таблица «как мастер называет деталь → где она в каталоге parts-catalogs».
 *
 * Зачем: поиск по похожести слов чинился по одной жалобе, и каждая правка
 * лечила одну формулировку на одной машине. Замер 23.09.2026 (`catalog:benchmark`,
 * 149 ходовых запросов × 11 машин пилота) дал 61% верных ответов: «помпа»
 * находилась, «насос водяной» — ни на одной машине, «гранатка» — на шести,
 * «шрус наружный» — ни на одной.
 *
 * На чём держится таблица (сверено по слепку каталога 11 машин, 23.09.2026):
 *   • у каталога есть универсальный справочник деталей, общий для ВСЕХ марок:
 *     «Насос - помпа системы охлаждения ДВС» — код 130 и у Subaru, и у Chery;
 *     1394 кода, у каждого ровно одно название. Деталь с кодом из строки
 *     таблицы — ровно та деталь, никаких соседей по узлу;
 *   • дерево узлов (`groups-tree`) тоже общее: помпа лежит в «Охлаждение ДВС >
 *     Насос  помпа системы охлаждения ДВС» у 8 машин из 11.
 * Код стоит не у всех деталей: у Subaru и Toyota — у 15-17%, остальное
 * по-английски («PAD KIT-FRONT DISK BRAKE»). Для деталей БЕЗ кода строка
 * держит запасной шаблон названия `other`; деталь с чужим кодом не
 * подходит никогда — код точнее любых слов.
 *
 * Номера деталей таблица не знает и не выдумывает: она только говорит, в
 * каком узле и под каким названием каталога искать. Всё, что видит мастер,
 * приходит из каталога.
 *
 * Порядок строк важен: берётся ПЕРВАЯ строка, чей `ask` подошёл, поэтому
 * уточнённые формулировки («датчик положения коленвала», «пыльник шруса»)
 * стоят раньше общих («коленвал», «шрус»).
 */
export type PartNode = {
  /** Формулировки мастера: проверяется на запросе в нижнем регистре, «ё» → «е». */
  ask: RegExp
  /** Коды универсального справочника каталога (`nameId` детали). */
  ids: string[]
  /** Название детали, у которой кода нет: русское или оригинальное английское. */
  other?: RegExp
  /** Чем деталь без кода, подошедшая под `other`, оказывается соседом (болт, пыльник). */
  not?: RegExp
  /** Куски пути листьев дерева, где деталь лежит, — в порядке охвата машин. */
  leaves: string[]
}

