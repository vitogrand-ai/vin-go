  'мы', 'на', 'найди', 'найдите', 'найти', 'нам', 'не', 'ни', 'но', 'нужен', 'нужна', 'нужно',
  'нужны', 'о', 'об', 'оригинал', 'оригиналы', 'оригинальная', 'оригинальные', 'оригинальный',
  'от', 'плиз', 'по', 'подскажи', 'подскажите', 'пож', 'пожалуйста', 'поиск', 'поищи', 'поищите',
  'пока', 'покажи', 'покажите', 'помоги', 'помогите', 'посмотри', 'посмотрите', 'предложи',
